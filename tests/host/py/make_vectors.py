#!/usr/bin/env python3
"""Generates the shared test vectors (spec task 14.5, Python half).

    python3 make_vectors.py [--seed N]

Writes tests/host/vectors/vectors.json (records, wire_vectors lines and bytes
for the Python and JavaScript codecs) and vectors/vectors.txt (the same lines
and decode lines, for `make -C tests/host vectors-c`). The seed is recorded in
the file; the same seed gives the same files. The bytes come from the C
Wire_Codec (build/wire_vectors) and are checked against the Python codec
before anything is written, so a file is never written from a codec that
disagrees with C.

Both files are committed. Property 28 (test_codec_cross.py, cross.test.js)
replays them through all three codecs.
"""

import argparse
import json
import random
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import codec_gen as gen  # noqa: E402
from codec_helpers import is02_codec as codec  # noqa: E402

OUT_DIR = HERE.parent / "vectors"
DEFAULT_SEED = 20261101

PER_KIND = {"telemetry": 30, "heartbeat": 20, "map": 20, "config": 12}
PER_CODE = {"event": 3, "ack": 4, "command": 4}


def valid_vectors(rng):
    out = []
    for kind in gen.KINDS:
        if kind in PER_CODE:
            codes = {"event": range(len(codec.EVENTS)), "ack": gen.ACK_CODES, "command": gen.COMMAND_CODES}[kind]
            recs = [gen.gen_record(kind, rng, code) for code in codes for _ in range(PER_CODE[kind])]
        else:
            recs = [gen.gen_record(kind, rng) for _ in range(PER_KIND[kind])]
        out += [(kind, rec) for rec in recs]
    # the empty and the full Map_Frame and Config_Frame, whatever the seed picked
    out.append(("map", gen.gen_map_body(rng, 0)))
    out.append(("map", gen.gen_map_body(rng, 4)))
    out.append(("config", {"count": 0, "pairs": []}))
    out.append(("config", {"count": codec.PARAM_COUNT,
                           "pairs": [[i, gen.finite_f32_bits(rng)] for i in range(codec.PARAM_COUNT)]}))
    return out


def bad_variants(data):
    """(why, bytes) for a valid frame: a wrong Format_Version, one byte short, one byte long, empty."""
    return [("bad_version", bytes([(data[0] & 0x0F) | (2 << 4)]) + data[1:]),
            ("short", data[:-1]),
            ("long", data + b"\x00"),
            ("empty", b"")]


def build(seed):
    rng = random.Random(seed)
    pairs = valid_vectors(rng)
    lines = [gen.line_of(kind, rec) for kind, rec in pairs]
    c_out = gen.c_lines(lines)
    vectors = []
    for (kind, rec), line, res in zip(pairs, lines, c_out):
        data = bytes.fromhex(res["hex"])
        if not data:
            raise SystemExit(f"C refused: {line}")
        if codec.encode_fields(kind, rec) != data:
            raise SystemExit(f"Python and C encode differently: {line}")
        vectors.append({"kind": kind, "record": rec, "line": line, "hex": data.hex()})
    seen = set()
    for vec in list(vectors):
        if vec["kind"] in seen:
            continue                        # one frame of each kind gets the bad variants
        seen.add(vec["kind"])
        for why, bad in bad_variants(bytes.fromhex(vec["hex"])):
            vectors.append({"kind": vec["kind"], "reject": why, "hex": bad.hex()})
    return vectors


def write(seed, vectors):
    OUT_DIR.mkdir(exist_ok=True)
    rows = ",\n".join("    " + json.dumps(v, separators=(",", ":")) for v in vectors)
    (OUT_DIR / "vectors.json").write_text(
        f'{{\n  "seed": {seed},\n  "format_version": {codec.FORMAT_VERSION},\n  "vectors": [\n{rows}\n  ]\n}}\n',
        encoding="utf-8", newline="\n")
    text = [f"# IS-02 shared vectors, seed {seed} (generated by py/make_vectors.py, do not edit)"]
    for v in vectors:
        if "line" in v:
            text.append(v["line"])
        text.append(gen.decode_line(v["kind"], bytes.fromhex(v["hex"])))
    (OUT_DIR / "vectors.txt").write_text("\n".join(text) + "\n", encoding="utf-8", newline="\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED)
    args = parser.parse_args()
    vectors = build(args.seed)
    write(args.seed, vectors)
    print(f"wrote {len(vectors)} vectors (seed {args.seed}) to {OUT_DIR}")


if __name__ == "__main__":
    main()
